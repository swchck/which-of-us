const LATIN_WORD = new RegExp(`(?<![A-Za-z])(${SPOKEN_LATIN.map(([w]) => escapeRegExp(w)).join('|')})(?![A-Za-z])`, 'g');
const SPOKEN = new Map(SPOKEN_LATIN);

/** Ordinals for the Roman centuries the content names, by the case the noun after them takes. */
const ROMAN: Record<string, { gen: string; prep: string }> = {
  XI: { gen: 'одиннадцатого', prep: 'одиннадцатом' },
  XIV: { gen: 'четырнадцатого', prep: 'четырнадцатом' },
  XIX: { gen: 'девятнадцатого', prep: 'девятнадцатом' },
  XX: { gen: 'двадцатого', prep: 'двадцатом' },
  XXI: { gen: 'двадцать первого', prep: 'двадцать первом' },
};

/**
 * Narrator text as a voice should read it: words and the punctuation that shapes intonation.
 * macOS voices spell out symbols they have no reading for («backslash» and friends), neural
 * engines stumble on quotes and dashes the same way, and Vosk cannot read digits at all.
 */
export function speechText(text: string): string {
  return text
    .replace(LATIN_WORD, (w) => SPOKEN.get(w)!)
    .replace(/(?<![A-Za-z])(XXI|XIX|XIV|XX|XI)\s+(век[аеу]?)(?!\p{L})/gu, (_, roman: string, noun: string) => `${noun === 'веке' ? ROMAN[roman]!.prep : ROMAN[roman]!.gen} ${noun}`)
    .replace(/Пётр I(?![A-Za-z])/gu, 'Пётр Первый')
    // «3D-очки» would come out as «триD»: voices read a lone Latin letter however they like
    .replace(/(\d)D(?![\p{L}])/gu, '$1-дэ')
    .replace(/(?<![\d.,])(\d{1,6})[.,](\d{1,2})(?![\d.,]?\d)/g, (_, whole: string, frac: string) => decimalWords(Number(whole), frac))
    .replace(/(?<!\d)\d{1,6}(?!\d)/g, (digits, offset: number, all: string) =>
      numberWords(Number(digits), GENITIVE_BEFORE.test(all.slice(0, offset))),
    )
    .replace(/[—–…·]/g, ', ')
    .replace(/[^\p{L}\p{N}\s.,!?:;'-]/gu, ' ')
    .replace(/\s+([.,!?:;])/g, '$1')
    .replace(/,(\s*,)+/g, ',')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Splits a narrator line into sentences. Each is synthesized and cached on its own, so the fixed
 * parts of a line («Голосуйте!», the question itself) come from cache and only the part with a
 * player's name needs a fresh render.
 */
export function speechSentences(text: string): string[] {
  return speechText(text)
    .split(/(?<=[.!?])\s+/)
    .map((s) => s.replace(/^[\s,.;:]+/, '').trim())
    .filter((s) => /[\p{L}\p{N}]/u.test(s));
}

