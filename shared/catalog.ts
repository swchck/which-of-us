const GEN_HUNDREDS = ['', 'ста', 'двухсот', 'трёхсот', 'четырёхсот', 'пятисот', 'шестисот', 'семисот', 'восьмисот', 'девятисот'];
/** Prepositions that put the number after them in the genitive: «от нуля до десяти», «один из четырёх». */
const GENITIVE_BEFORE = /(?:^|[^\p{L}])(?:от|до|из|без|около|кроме|для|у|больше|меньше)\s+$/iu;

/** 1..999 in words; `fem` agrees a final one or two with a feminine noun («одна тысяча»). */
function hundreds(n: number, gen: boolean, fem: boolean): string[] {
  const [h, t, o] = [Math.floor(n / 100), Math.floor(n / 10) % 10, n % 10];
  const words = [(gen ? GEN_HUNDREDS : NUM_HUNDREDS)[h]!];
  if (t === 1) return [...words, (gen ? GEN_TEENS : NUM_TEENS)[o]!].filter(Boolean);
  words.push((gen ? GEN_TENS : NUM_TENS)[t]!);
  if (fem && o === 1) words.push(gen ? 'одной' : 'одна');
  else if (fem && o === 2 && !gen) words.push('две');
  else words.push((gen ? GEN_ONES : NUM_ONES)[o]!);
  return words.filter(Boolean);
}

/** A whole number below a million in Russian words, nominative or genitive. */
export function numberWords(n: number, gen = false, fem = false): string {
  if (n === 0) return gen ? 'нуля' : 'ноль';
  const [k, rest] = [Math.floor(n / 1000), n % 1000];
  const words: string[] = [];
  if (k > 0) {
    const last = k % 10;
    const teen = k % 100 >= 11 && k % 100 <= 14;
    const noun = gen ? (last === 1 && !teen ? 'тысячи' : 'тысяч') : teen || last === 0 || last > 4 ? 'тысяч' : last === 1 ? 'тысяча' : 'тысячи';
    words.push(...hundreds(k, gen, true), noun);
  }
  if (rest > 0) words.push(...hundreds(rest, gen, fem));
  return words.join(' ');
}

/** «3.5» as «три целых пять десятых»; fractions are feminine, so the whole part agrees with «целая». */
function decimalWords(whole: number, frac: string): string {
  const f = Number(frac);
  const part = frac.length === 1 ? 'десят' : 'сот';
  const plural = (x: number) => (x % 10 === 1 && x % 100 !== 11 ? 'ая' : 'ых');
  return `${numberWords(whole, false, true)} цел${plural(whole)} ${numberWords(f, false, true)} ${part}${plural(f)}`;
}

