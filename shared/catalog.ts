/** Russian typography groups digits from five up: «1997» and «1440», but «86 400». */
export function formatNumber(n: number): string {
  return Math.abs(n) >= 10_000 ? n.toLocaleString('ru') : String(n);
}

/** The unit agreeing with the number in Russian: «год» for 1, «года» for 4, «лет» for 116; abbreviations stay as they are. */
export function unitFor(n: number, unit: string): string {
  const forms = UNIT_FORMS[unit];
  if (!forms) return unit;
  const tens = n % 100;
  const ones = n % 10;
  if (tens >= 11 && tens <= 14) return forms[2];
  if (ones === 1) return forms[0];
  return ones >= 2 && ones <= 4 ? forms[1] : forms[2];
}

/** The number with its agreeing unit, e.g. «4 года». */
export function withUnit(n: number, unit?: string): string {
  const text = formatNumber(n);
  return unit ? `${text} ${unitFor(n, unit)}` : text;
}

/**
 * Drops control and invisible formatting characters, and angle brackets. The zero-width joiner stays:
 * it glues family and profession emoji together, and stripping it would split them apart.
 */
export function stripControls(text: string): string {
  return text.replace(/[\p{Cc}\p{Cs}\p{Co}\p{Cn}\u200B\u200E\u200F\u202A-\u202E\u2066-\u2069<>]/gu, '');
}

const normalized = (s: string) => stripControls(s).toLowerCase().replaceAll('ё', 'е');

/** Words of a «Три слова» clue: a hyphenated compound like «вверх-вниз» counts as one. */
export function clueWords(clue: string): string[] {
  return normalized(clue)
    .split(/\s+/)
    .filter((w) => /[\p{L}\p{N}]/u.test(w));
}

/** Why a «Три слова» clue cannot be sent for this word, or null when it is fine. */
/** Reports whether a hint names the word or a word of the same root. */
export function givesAway(word: string, hint: string): boolean {
  // the word minus its last two letters, three to five long: catches «кошачий» for «кошка» and «лунный»
  // for «Луна», and now and then bans an unrelated word that only starts alike, a fair price at a party
  const stems = normalized(word)
    .split(/[^\p{L}]+/u)
    .filter((w) => w.length >= 3)
    .map((w) => w.slice(0, Math.min(5, Math.max(3, w.length - 2))));
  const parts = clueWords(hint).flatMap((w) => w.split(/[^\p{L}\p{N}]+/u));
  return parts.some((p) => stems.some((s) => p.startsWith(s)));
}

export function clueProblem(word: string, clue: string): string | null {
  const words = clueWords(clue);
  if (words.length === 0) return 'Напишите подсказку';
  if (words.length > CLUE_WORDS) return `Не больше ${CLUE_WORDS} слов`;
  if (givesAway(word, clue)) return 'Без самого слова и однокоренных';
  return null;
}

/** Normal form of a «Кто больше» answer, so «Ёжик», «ежик» and «ёжик!» count as one. */
export function listKey(text: string): string {
  return normalized(text)
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .replace(/\s+/g, ' ')
    .trim();
}

