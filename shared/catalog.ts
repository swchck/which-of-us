function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Splits a spoken sentence around player names: the text pieces, trimmed of the punctuation at
 * their edges, and the names themselves, in order. Pieces without letters are dropped. A slow
 * voice says the pieces and the name apart from cache instead of rendering the whole sentence.
 */
export function speechPieces(sentence: string, names: readonly string[]): string[] {
  const spoken = [...new Set(names.map(speechText).filter(Boolean))].sort((a, b) => b.length - a.length);
  if (spoken.length === 0) return [sentence];
  const re = new RegExp(`(?<![\\p{L}])(${spoken.map(escapeRegExp).join('|')})(?![\\p{L}])`, 'u');
  return sentence
    .split(re)
    .map((p, i) => (i % 2 === 1 ? p : p.replace(/^[\s,.;:!?-]+|[\s,;:-]+$/g, '')))
    .filter((p) => /\p{L}/u.test(p));
}

