/**
 * Block capitals as one stroke path, `size` tall from the baseline `y` up, for signs: SVG text would
 * fall back to whatever font the TV has. Covers Cyrillic capitals, digits and `! ? : . -`.
 */
export function strokeText(text: string, x: number, y: number, size: number, anchor: 'start' | 'middle' = 'start'): string {
  const u = size / 6;
  const gap = 1.7;
  const glyphs = [...text.toUpperCase()].map((ch) => GLYPHS[ch] ?? GLYPHS[' ']!);
  const width = glyphs.reduce((w, [, gw = 4]) => w + gw + gap, -gap) * u;
  let left = anchor === 'middle' ? x - width / 2 : x;
  const top = y - size;
  let d = '';
  for (const [strokes, gw = 4] of glyphs) {
    for (const s of strokes) d += s.map(([gx, gy], i) => `${i ? 'L' : 'M'}${(left + gx * u).toFixed(1)} ${(top + gy * u).toFixed(1)}`).join(' ') + ' ';
    left += (gw + gap) * u;
  }
  return d.trim();
}
