/** Deterministic random numbers, so a scene looks the same on every TV and every reload. */
export function seeded(seed: number): () => number {
  let a = seed;
  return () => {
    a = (a * 16807) % 2147483647;
    return a / 2147483647;
  };
}

/** Splits items into four groups that blink out of phase: four animated nodes repaint far cheaper than one per star. */
export function twinkleGroups<T>(items: T[]): T[][] {
  return [0, 1, 2, 3].map((g) => items.filter((_, i) => i % 4 === g));
}

/** Grass blades along a gently sloped ridge: little V strokes, spaced unevenly so they read as drawn. */
export function tufts(x0: number, y: number, x1: number, slope: number): string {
  let d = '';
  for (let x = x0, i = 0; x < x1; x += 70 + ((i * 37) % 50), i++) {
    const top = y + Math.sin(x * slope) * 10;
    d += `M${x - 10} ${top + 4} L${x - 4} ${top - 12} M${x} ${top + 4} L${x + 2} ${top - 16} M${x + 10} ${top + 4} L${x + 8} ${top - 10} `;
  }
  return d;
}

